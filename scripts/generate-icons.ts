#!/usr/bin/env tsx
/**
 * Generate the picture files that come from Lucide glyphs:
 *
 *  - imgs/actions/<id>/icon.svg  20x20 white action-list icon
 *  - imgs/actions/<id>/key.svg   144x144 neutral placeholder tile (generic glyph, no text,
 *                                no brand); shown until the first real paint and as the
 *                                manifest default
 *  - src/render/generated/glyphs.ts  inner markup of every glyph the renderers draw,
 *                                so the single-file bundle needs no file reads at runtime
 *  - imgs/icons/LICENSE-lucide.txt  Lucide's ISC licence (plus the MIT notice for the
 *                                Feather-derived icons it lists) with a note which of
 *                                the used icons fall under which
 *
 * Deterministic: no timestamps, stable ordering. Usage: npm run generate:icons
 */

import { copyFileSync, mkdirSync, readFileSync, writeFileSync, appendFileSync } from "node:fs";
import { resolve } from "node:path";
import { ACTION_IDS, DIAL_SPEC, FOCUS_SPECS, KEYPAD_SPECS, catalogGlyphs, type ActionId } from "../src/actions/catalog.ts";
import { GLYPH_NAMES } from "../src/render/glyph-names.ts";
import { PLUGIN_DIR, PROJECT_ROOT } from "./lib/plugin-id.ts";

const LUCIDE_ROOT = resolve(PROJECT_ROOT, "node_modules/lucide-static");
const LUCIDE_DIR = resolve(LUCIDE_ROOT, "icons");
const GLYPH_MODULE = resolve(PROJECT_ROOT, "src/render/generated/glyphs.ts");
const ACTIONS_IMG_DIR = resolve(PLUGIN_DIR, "imgs/actions");

/** Inner markup of a Lucide SVG (paths, circles, ...), whitespace collapsed. */
function lucideInner(name: string): string {
	const raw = readFileSync(resolve(LUCIDE_DIR, `${name}.svg`), "utf-8");
	const m = raw.replace(/<!--[\s\S]*?-->/g, "").match(/<svg[^>]*>([\s\S]*?)<\/svg>/);
	if (!m) throw new Error(`Could not parse Lucide icon: ${name}`);
	return m[1]!.replace(/\s+/g, " ").trim();
}

function listIcon(glyph: string): string {
	return (
		`<svg xmlns="http://www.w3.org/2000/svg" width="20" height="20" viewBox="0 0 24 24" fill="none" ` +
		`stroke="#FFFFFF" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${lucideInner(glyph)}</svg>\n`
	);
}

/** Neutral placeholder tile: no accent colour, no text. */
function placeholderKey(glyph: string): string {
	return (
		`<svg xmlns="http://www.w3.org/2000/svg" width="144" height="144" viewBox="0 0 144 144">` +
		`<rect width="144" height="144" rx="18" fill="#1A1A1A"/>` +
		`<g transform="translate(32,32) scale(3.3333)" fill="none" stroke="#C8CDD3" stroke-width="2" ` +
		`stroke-linecap="round" stroke-linejoin="round">${lucideInner(glyph)}</g></svg>\n`
	);
}

function glyphOf(id: ActionId): string {
	if (id === DIAL_SPEC.id) return DIAL_SPEC.glyph;
	return (KEYPAD_SPECS.find((s) => s.id === id) ?? FOCUS_SPECS.find((s) => s.id === id)!).glyph;
}

let written = 0;
for (const id of ACTION_IDS) {
	const dir = resolve(ACTIONS_IMG_DIR, id);
	mkdirSync(dir, { recursive: true });
	writeFileSync(resolve(dir, "icon.svg"), listIcon(glyphOf(id)), "utf-8");
	writeFileSync(resolve(dir, "key.svg"), placeholderKey(glyphOf(id)), "utf-8");
	written += 2;
}

// Glyph module: the renderers' list plus whatever the catalog needs, sorted for stable output.
const names = [...new Set<string>([...GLYPH_NAMES, ...catalogGlyphs()])].sort();
const entries = names.map((name) => `\t${JSON.stringify(name)}: ${JSON.stringify(lucideInner(name))},`).join("\n");
mkdirSync(resolve(PROJECT_ROOT, "src/render/generated"), { recursive: true });
writeFileSync(
	GLYPH_MODULE,
	`// GENERATED by scripts/generate-icons.ts - do not edit.\n` +
		`//\n` +
		`// Inner markup of each Lucide glyph the renderers draw (Lucide's 24x24 space), so the\n` +
		`// single-file bundle needs no file reads at runtime. Regenerate: npm run generate:icons\n\n` +
		`import type { GlyphName } from "../glyph-names.ts";\n\n` +
		`export const GLYPHS: Readonly<Record<GlyphName, string>> = {\n${entries}\n};\n`,
	"utf-8",
);
written += 1;

// Licence: Lucide's own file already carries the ISC text and, below it, the MIT notice
// for icons derived from Feather together with the list of those icons.
const licenceSource = readFileSync(resolve(LUCIDE_ROOT, "LICENSE"), "utf-8");
const featherList = new Set(
	(/derived from the Feather project:\s*([\s\S]*?)\n\s*\nThe MIT License/.exec(licenceSource)?.[1] ?? "")
		.split(",")
		.map((s) => s.trim())
		.filter(Boolean),
);
if (featherList.size === 0) throw new Error("could not read the Feather icon list from Lucide's LICENSE");

/**
 * Lucide renamed some icons and lists the OLD name in the Feather list; the aliases
 * below map new -> old for the icons this plugin uses (both file names exist in the
 * installed package). Anything not listed is looked up under its own name.
 */
const FEATHER_ALIASES: Record<string, string> = {
	"triangle-alert": "alert-triangle",
	"circle-help": "help-circle",
	"circle-arrow-right": "arrow-right-circle",
	"circle-arrow-left": "arrow-left-circle",
};

const usedFeather = names.filter((n) => featherList.has(n) || featherList.has(FEATHER_ALIASES[n] ?? ""));
const usedLucideOnly = names.filter((n) => !usedFeather.includes(n));

mkdirSync(resolve(PLUGIN_DIR, "imgs/icons"), { recursive: true });
const licenceTarget = resolve(PLUGIN_DIR, "imgs/icons/LICENSE-lucide.txt");
copyFileSync(resolve(LUCIDE_ROOT, "LICENSE"), licenceTarget);
appendFileSync(
	licenceTarget,
	`\n---\n\n` +
		`Note for this plugin (generated by scripts/generate-icons.ts):\n\n` +
		`The plugin draws the following Lucide icons. Those listed as Feather-derived come from the\n` +
		`Feather project and are therefore additionally covered by the MIT notice above\n` +
		`(Copyright (c) 2013-present Cole Bemis); the others fall under the ISC licence only.\n\n` +
		`Feather-derived: ${usedFeather.join(", ") || "(none)"}\n` +
		`ISC only:        ${usedLucideOnly.join(", ") || "(none)"}\n`,
);
written += 1;

console.log(`Generated ${written} files: ${ACTION_IDS.length} actions, ${names.length} glyphs.`);
